#!/usr/bin/env python3
"""Fetches the open-licence (SIL OFL) web fonts used by the six designs from npm
(@fontsource packages), keeps the Latin + Latin Extended subsets (Turkish needs
ş ğ ı İ and ₺ from Latin Extended) and writes fonts/fonts.css.

    python3 tools/get_fonts.py
"""
import pathlib
import re
import shutil
import subprocess
import tarfile
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / 'fonts'
WANT = {
    'space-grotesk': ['500', '700'],
    'jetbrains-mono': ['400', '700', '800'],
    'playfair-display': ['400', '700', '900', '400-italic', '700-italic'],
    'anton': ['400'],
    'sora': ['400', '600', '700', '800'],
    'unbounded': ['400', '600', '800'],
    'dm-serif-display': ['400', '400-italic'],
    'manrope': ['500', '600', '700', '800'],
}
KEEP = re.compile(r'-(latin|latin-ext)-\d+-(normal|italic)\b')


def main():
    css = []
    with tempfile.TemporaryDirectory() as tmp:
        for pkg, weights in WANT.items():
            subprocess.run(['npm', 'pack', f'@fontsource/{pkg}', '--silent'], cwd=tmp, check=True, capture_output=True)
            tgz = next(pathlib.Path(tmp).glob(f'fontsource-{pkg}-*.tgz'))
            d = pathlib.Path(tmp) / pkg
            with tarfile.open(tgz) as tf:
                tf.extractall(d, filter='data')
            src = d / 'package'
            dst = OUT / pkg
            dst.mkdir(parents=True, exist_ok=True)
            shutil.copy(src / 'LICENSE', dst / 'LICENSE')
            for w in weights:
                text = (src / f'{w}.css').read_text()
                for block in re.findall(r'/\*[^*]*\*/\s*@font-face\s*{[^}]*}', text):
                    if not KEEP.search(block):
                        continue
                    for f in re.findall(r'url\(\./files/([^)]+\.woff2)\)', block):
                        shutil.copy(src / 'files' / f, dst / f)
                    block = re.sub(r"src: url\(\./files/([^)]+\.woff2)\) format\('woff2'\), url\([^)]*\) format\('woff'\);",
                                   lambda m: f"src: url({pkg}/{m.group(1)}) format('woff2');", block)
                    block = block.replace('font-display: swap;', 'font-display: block;')
                    css.append(block)
    # Inter / Inter Display (already in the repo, OTF)
    inter = ROOT.parent / 'allinvestview-showreel' / 'fonts'
    (OUT / 'inter').mkdir(exist_ok=True)
    for f in inter.glob('*'):
        shutil.copy(f, OUT / 'inter' / f.name)
    for fam, f, w in [('Inter Display', 'InterDisplay-Black.otf', 900), ('Inter Display', 'InterDisplay-ExtraBold.otf', 800),
                      ('Inter Display', 'InterDisplay-Bold.otf', 700), ('Inter', 'Inter-Bold.otf', 700),
                      ('Inter', 'Inter-SemiBold.otf', 600), ('Inter', 'Inter-Medium.otf', 500)]:
        css.append(f"@font-face {{ font-family: '{fam}'; font-weight: {w}; font-display: block; src: url(inter/{f}); }}")
    (OUT / 'fonts.css').write_text('/* Generated by tools/get_fonts.py */\n' + '\n'.join(css) + '\n')
    print(f'{len(css)} @font-face rules → {OUT / "fonts.css"}')


if __name__ == '__main__':
    main()
